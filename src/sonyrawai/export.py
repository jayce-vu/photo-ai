"""16-bit TIFF / JPEG preview / JSON sidecar export with atomic writes and readback validation.

TIFF: RGB, uint16, exact decoded width/height, sRGB-encoded values, embedded sRGB ICC profile
(generated by Pillow/LittleCMS), deflate compression. Orientation is already applied at decode.
"""

from __future__ import annotations

import hashlib
import json
import os
import shutil
import tempfile
from pathlib import Path
from typing import Any

import numpy as np
import tifffile

from .color import srgb_encode


class ExportValidationError(RuntimeError):
    pass


def srgb_icc_profile() -> bytes | None:
    try:
        from PIL import ImageCms

        return ImageCms.ImageCmsProfile(ImageCms.createProfile("sRGB")).tobytes()
    except Exception:  # pragma: no cover - Pillow built without LittleCMS
        return None


def quantize_uint16(linear: np.ndarray) -> np.ndarray:
    """Linear float [0,1] -> sRGB-encoded uint16. Rejects NaN/Inf/out-of-range BEFORE quantisation."""
    if linear.ndim != 3 or linear.shape[2] != 3:
        raise ExportValidationError(f"export expects HxWx3 RGB, got {linear.shape}")
    if not np.isfinite(linear).all():
        raise ExportValidationError("image contains NaN/Inf before quantisation")
    if linear.min() < -1e-6 or linear.max() > 1 + 1e-6:
        raise ExportValidationError(f"image out of [0,1] before quantisation: {linear.min()}..{linear.max()}")
    return np.rint(srgb_encode(linear) * 65535.0).astype(np.uint16)


def _umask() -> int:
    mask = os.umask(0)
    os.umask(mask)
    return mask


def _tmp_path(dest: Path) -> Path:
    """Temp file next to ``dest`` (same filesystem -> atomic os.replace), normal file permissions."""
    fd, name = tempfile.mkstemp(prefix=f".{dest.name}.", suffix=".tmp", dir=dest.parent)
    os.close(fd)
    os.chmod(name, 0o666 & ~_umask())
    return Path(name)


def atomic_write_bytes(dest: Path, data: bytes) -> None:
    dest = Path(dest)
    dest.parent.mkdir(parents=True, exist_ok=True)
    tmp = _tmp_path(dest)
    try:
        tmp.write_bytes(data)
        os.replace(tmp, dest)
    finally:
        tmp.unlink(missing_ok=True)


def atomic_write_json(dest: Path, obj: Any) -> None:
    atomic_write_bytes(dest, (json.dumps(obj, indent=2, sort_keys=True, default=str) + "\n").encode("utf-8"))


def atomic_copy(src: Path, dest: Path) -> None:
    """Copy to a temp name in the destination folder, then rename (safe for Google Drive FUSE)."""
    dest = Path(dest)
    dest.parent.mkdir(parents=True, exist_ok=True)
    tmp = _tmp_path(dest)
    try:
        shutil.copyfile(src, tmp)
        if tmp.stat().st_size != Path(src).stat().st_size:
            raise ExportValidationError(f"copy of {src} truncated")
        os.replace(tmp, dest)
    finally:
        tmp.unlink(missing_ok=True)


def array_digest(arr: np.ndarray) -> str:
    return hashlib.sha256(np.ascontiguousarray(arr).tobytes()).hexdigest()


def write_tiff16(dest: Path, rgb16: np.ndarray, embed_icc: bool = True) -> dict[str, Any]:
    if rgb16.dtype != np.uint16 or rgb16.ndim != 3 or rgb16.shape[2] != 3:
        raise ExportValidationError(f"TIFF writer expects HxWx3 uint16, got {rgb16.shape} {rgb16.dtype}")
    dest = Path(dest)
    dest.parent.mkdir(parents=True, exist_ok=True)
    icc = srgb_icc_profile() if embed_icc else None
    tmp = _tmp_path(dest)
    try:
        kwargs: dict[str, Any] = {"photometric": "rgb", "compression": "zlib", "metadata": None,
                                  "resolution": (300, 300), "resolutionunit": "INCH"}
        if icc:
            kwargs["iccprofile"] = icc
        tifffile.imwrite(tmp, rgb16, **kwargs)
        info = validate_tiff(tmp, rgb16.shape, expected_digest=array_digest(rgb16))
        os.replace(tmp, dest)
        info["path"] = str(dest)
    finally:
        tmp.unlink(missing_ok=True)
    info["icc_profile"] = "sRGB (LittleCMS built-in)" if icc else None
    return info


def validate_tiff(path: Path, expected_shape: tuple[int, ...], expected_digest: str | None = None) -> dict[str, Any]:
    path = Path(path)
    if not path.is_file() or path.stat().st_size == 0:
        raise ExportValidationError(f"TIFF missing or empty: {path}")
    with tifffile.TiffFile(path) as tf:
        page = tf.pages[0]
        arr = page.asarray()
        photometric = int(page.photometric)
    if arr.dtype != np.uint16:
        raise ExportValidationError(f"readback dtype {arr.dtype}, expected uint16")
    if arr.shape != tuple(expected_shape):
        raise ExportValidationError(f"readback shape {arr.shape}, expected {tuple(expected_shape)}")
    if photometric != int(tifffile.PHOTOMETRIC.RGB):
        raise ExportValidationError(f"readback photometric {photometric}, expected RGB")
    if expected_digest is not None and array_digest(arr) != expected_digest:
        raise ExportValidationError("TIFF readback pixels differ from written pixels")
    return {"path": str(path), "bytes": path.stat().st_size, "dtype": "uint16",
            "shape": list(arr.shape), "photometric": "RGB", "pixel_sha256": array_digest(arr)}


def write_jpeg_preview(dest: Path, rgb16: np.ndarray, max_side: int = 2048, quality: int = 90) -> str:
    """Optional 8-bit preview. Never a substitute for the TIFF deliverable."""
    from PIL import Image

    img = Image.fromarray((rgb16 >> 8).astype(np.uint8), mode="RGB")
    img.thumbnail((max_side, max_side), Image.Resampling.LANCZOS)
    dest = Path(dest)
    dest.parent.mkdir(parents=True, exist_ok=True)
    tmp = _tmp_path(dest)
    try:
        icc = srgb_icc_profile()
        img.save(tmp, format="JPEG", quality=quality, icc_profile=icc) if icc else img.save(
            tmp, format="JPEG", quality=quality)
        os.replace(tmp, dest)
    finally:
        tmp.unlink(missing_ok=True)
    return str(dest)


def sidecar_path(tiff_path: Path) -> Path:
    return Path(tiff_path).with_suffix(".json")
